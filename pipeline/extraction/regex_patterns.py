"""字段抽取正则模式库。"""

import re
from pathlib import Path


def _sp(label: str) -> str:
    """构造允许字间夹杂空白的标签正则。

    OCR/PDF 抽取的公示表表头常见逐字加空格或换行（如「受 处 罚 单 位 名 称」
    「被处罚当事\\n人」），若按字面量精确匹配会导致标签整体 NOMATCH。
    对标签中每个字符之间插入可选空白（含换行/全角空格）。
    """
    return r"\s*".join(re.escape(ch) for ch in label)


# 违法事实描述常跨多行（OCR/PDF 逐行断行），需用 [\s\S] 跨行匹配；
# 用以下"转折短语"作为终止边界（进入法律依据/处罚决定部分即停止），
# 避免把处罚依据、处罚决定文字也吞进 violation_behavior。
_VIOLATION_STOP = (
    r"(?:"
    r"你(?:公司|单位|机构)?[^\n]{0,20}(?:上述行为)?违反"
    r"|上述(?:行为|事实)(?:[，,])?(?:已)?违反"
    r"|违反(?:了)?《"
    r"|已构成[^\n]{0,10}(?:情形|行为)"
    r"|根据《"
    r"|依据《"
    r"|依照《"
    r"|《中华人民共和国"
    r"|行政处罚依据"
    r"|行政处罚决定"
    r"|作出处罚决定"
    r"|我(?:会|局|处|厅)(?:认为|决定|拟)"
    r"|本机关(?:认为|决定)"
    r"|经研究决定"
    r"|经审议决定"
    r"|综上"
    r")"
)

# 当事人标签：长标签必须排在短标签之前，避免「受处罚人」吃掉「受处罚人名称」。
# 「被处罚*」与「受处罚*」两套称谓都要覆盖（各地文书用词不统一）。
_PARTY_LABEL = (
    r"(?:"
    + _sp("当事人单位名称") + r"|" + _sp("当事人名称") + r"|" + _sp("当事人单位") + r"|"
    + _sp("被处罚单位名称") + r"|" + _sp("受处罚单位名称") + r"|"
    + _sp("被处罚人名称") + r"|" + _sp("受处罚人名称") + r"|"
    + _sp("被处罚单位") + r"|" + _sp("受处罚单位") + r"|"
    + _sp("被处罚当事人") + r"|" + _sp("受处罚当事人") + r"|"
    + _sp("被处罚人") + r"|" + _sp("受处罚人") + r"|"
    + _sp("当事人") + r")"
)

# 决定书抬头常见「名称:XXX公司」（无当事人前缀）
_NAME_ONLY_LABEL = _sp("名称")

_VIOLATION_LABEL = (
    r"(?:" + _sp("主要违法违规事实") + r"|" + _sp("主要违法违规行为") + r"|"
    + _sp("违法违规事实") + r"|" + _sp("违法违规行为") + r"|"
    + _sp("违法事实") + r"|" + _sp("违法行为") + r"|"
    + _sp("违规事实") + r"|" + _sp("违规行为") + r")"
)

_PENALTY_LABEL = (
    r"(?:" + _sp("行政处罚决定") + r"|" + _sp("行政处罚内容") + r"|" + _sp("行政处罚意见") + r"|"
    + _sp("处罚决定") + r"|" + _sp("处罚内容") + r"|" + _sp("处罚意见") + r")"
)

_REGULATOR_LABEL = (
    r"(?:" + _sp("作出处罚决定的机关名称") + r"|" + _sp("作出处罚决定的机关") + r"|"
    + _sp("处罚机关") + r"|" + _sp("决定机关") + r"|" + _sp("作出机关") + r")"
)

PATTERNS = {
    "penalty_doc_no": re.compile(
        r"([\u4e00-\u9fff]{0,8}(?:金罚决字|罚决字|银保监罚决字|银保监罚|保监罚决字|保监罚|罚字)"
        r"[〔\[（(]\d{4}[〕\]）)]\s*第?\s*\d+\s*号)"
    ),

    # 当事人：覆盖决定书/公示表多种写法，标签本身容忍逐字空格/换行（OCR 表头常见）。
    # 标签后必须有冒号或空白分隔，避免「被处罚人名称的划款凭证」这类正文误命中。
    # 排除逗号：公示表常紧跟「，地址XX，负责人XX」，逗号后不属于主体名称。
    "party_name": re.compile(
        _PARTY_LABEL + r"[：:\s]+([^\n。；;，,]{2,80})"
    ),
    # 决定书抬头「名称:XXX公司」（无当事人前缀），限制在文首 400 字内降低误伤。
    # 排除「机关名称/单位名称」等复合词尾部的「名称」，避免把监管机关误当当事人。
    "party_name_title": re.compile(
        r"(?s)\A.{0,400}?(?<![机关单位部处科])" + _NAME_ONLY_LABEL
        + r"[：:\s]+([^\n。；;，,]{4,80})"
    ),
    "party_name_alt": re.compile(
        r"(?:经查[，,]?\s*|对)([\u4e00-\u9fffA-Za-z0-9（）()]{4,60}?"
        r"(?:保险|人寿|财险|产险)[\u4e00-\u9fffA-Za-z0-9（）()]{0,40}"
        r"(?:公司|支公司|分公司|中心支公司))"
    ),
    # 标题/括号兜底：决定书标题常含「……决定书(XXX公司)」或「——XXX公司」
    # 允许表名与括号当事人之间有换行（OCR 公示表常见）。
    "party_name_header": re.compile(
        r"(?:行政处罚决定书|行政处罚信息公开表|行政处罚信息|处罚决定书)"
        r"[^\n（(\-—–]{0,40}?"
        r"(?:[（(\-—–]|\s*[（(])"
        r"\s*([\u4e00-\u9fffA-Za-z0-9（）()]{4,60}?"
        r"(?:保险|人寿|财险|产险|经纪|代理|公估)[\u4e00-\u9fffA-Za-z0-9（）()]{0,40}"
        r"(?:公司|支公司|分公司|中心支公司|营业部|服务部))"
    ),

    # 主分支：懒惰匹配至转折短语（跨行）；找不到转折短语则退化为定长跨行截取，
    # 保证长文本仍能抓到完整违法事实枚举（而不是被首个换行截断为几个字）。
    "violation_behavior": re.compile(
        # 公示表常见「主要违法违规事实(案由)」后直接换行枚举，无冒号
        _VIOLATION_LABEL + r"(?:[（(][^）)]*[）)])?(?:[：:]\s*|\s*\n\s*|\s+)"
        r"(?:([\s\S]{10,1200}?)(?=" + _VIOLATION_STOP + r")|([\s\S]{10,700}))"
    ),
    "violation_behavior_alt": re.compile(
        r"(?:存在(?:以下|下列)?(?:违法|违规)行为[：:]?\s*|经查[，,]?\s*)"
        r"(?:([\s\S]{8,1200}?)(?=" + _VIOLATION_STOP + r")|([\s\S]{8,500}))"
    ),

    "penalty_content": re.compile(
        # 公示表常见「行政处罚决定」与内容分两行或粘连（无冒号），故允许换行/空白分隔
        _PENALTY_LABEL + r"(?:[：:]\s*|\s*\n\s*|\s+)([^\n]{1,400})"
    ),
    # 处罚决定句常跨行且以「。」收尾，用 [^。] 天然跨行、并锚定在具体处罚动作词上，
    # 避免吞并前面的违法事实枚举。表格式短句常无句号，故句号可选。
    "penalty_content_alt": re.compile(
        r"((?:我(?:会|局|处|厅)|本机关|经研究决定|经审议决定)?[^。]{0,20}?"
        r"(?:决定(?:给予|对)?|给予|处以|责令|作出)[^。]{0,40}?"
        r"(?:罚款|警告|没收违法所得|吊销(?:业务)?许可证|"
        r"暂停[^。]{0,10}业务|停止接受[^。]{0,30}(?:新)?业务)[^。]{0,120}。?)"
    ),

    "fine_amount": re.compile(
        r"罚款\s*(?:人民币|合计)?\s*([\d,.]+\s*(?:万|千|百)?\s*元)"
    ),

    "regulator": re.compile(
        _REGULATOR_LABEL + r"[：:\s]*([\u4e00-\u9fff]{4,50}?(?:监管局|监管分局|银保监局|金融监督管理总局"
        r"[\u4e00-\u9fff]{0,12}|保监局|银保监会|保监会))"
    ),

    # 两处易错点：
    # 1) 地区前缀长度上限须收紧（真实省市自治州名最长 3～4 字，如「黔西南」
    #    「张家口」）；若放宽到 8～10 会在「之日起六十日内向山东银保监局申请
    #    行政复议」这类申诉条款里，把「之日起六十日内向」也贪婪吃进地区前缀。
    # 2) 后缀「监管局/监管分局」必须写成必选分支、不能是「前缀贪婪 + 后缀可选」
    #    的组合——可选后缀会让贪婪前缀在没有后缀时也照样匹配成功，从而把紧邻
    #    的下一个无关字（如「……监管局行政处罚决定书」里的「行」）也吞进结果，
    #    污染后续"取最长匹配"时的长度比较。故每个地区级机关名都拆成
    #    「XX+监管分局」「XX+监管局」「XX」三条固定后缀分支，按由长到短排列。
    "regulator_inline": re.compile(
        r"(国家金融监督管理总局[\u4e00-\u9fff]{0,6}?监管分局"
        r"|国家金融监督管理总局[\u4e00-\u9fff]{0,6}?监管局"
        r"|国家金融监督管理总局"
        r"|中国银保监会[\u4e00-\u9fff]{0,6}?监管分局"
        r"|中国银保监会[\u4e00-\u9fff]{0,6}?监管局"
        r"|中国银保监会"
        # 「中国保监会」此前只有裸词分支，缺少带地区的「XX监管局/监管分局」形式，
        # 导致遇到「中国保监会重庆监管局」时只能退化匹配到末尾的裸词分支。
        r"|中国保监会[\u4e00-\u9fff]{0,6}?监管分局"
        r"|中国保监会[\u4e00-\u9fff]{0,6}?监管局"
        r"|中国保监会"
        r"|[\u4e00-\u9fff]{2,6}银保监局"
        r"|[\u4e00-\u9fff]{2,6}保监局)"
    ),

    "publish_date": re.compile(
        r"(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日"
    ),

    "legal_basis": re.compile(
        r"((?:依据|根据)\s*《[^》]{2,40}》[^\n。；;]{0,100})"
    ),
}

