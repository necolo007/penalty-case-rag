"""字段抽取正则模式库。"""

import re

PATTERNS = {
    # 行政处罚决定书文号：鲁金罚决字〔2026〕16号 / 银保监罚决字〔2023〕5号
    "penalty_doc_no": re.compile(
        r"([\u4e00-\u9fff]{1,8}(?:金罚决字|罚决字|银保监罚|保监罚|罚字)"
        r"[〔\[（(]\d{4}[〕\]）)]\s*第?\s*\d+\s*号)"
    ),

    # 当事人名称
    "party_name": re.compile(
        r"当事人[：:]\s*([^\n。；;]{2,60})"
    ),

    # 违法违规行为
    "violation_behavior": re.compile(
        r"(?:主要)?(?:违法|违规|违法违规)\s*(?:事实|行为)[：:]\s*([^\n]{1,500})"
    ),

    # 处罚内容
    "penalty_content": re.compile(
        r"(?:行政)?处罚\s*(?:决定|内容)[：:]\s*([^\n]{1,300})"
    ),

    # 罚款金额
    "fine_amount": re.compile(
        r"罚款\s*(?:人民币)?\s*([\d,.]+\s*(?:万|千|百)?\s*元)"
    ),

    # 作出处罚机关
    "regulator": re.compile(
        r"(?:作出处罚决定的机关(?:名称)?|处罚机关|决定机关)[：:]\s*"
        r"([\u4e00-\u9fff]{4,40}?(?:监管局|监管分局|银保监局|金融监督管理总局[\u4e00-\u9fff]{0,10}|保监局))"
    ),

    # 兜底：正文中出现的监管机构名
    "regulator_inline": re.compile(
        r"(国家金融监督管理总局[\u4e00-\u9fff]{0,10}(?:监管局|监管分局)?"
        r"|[\u4e00-\u9fff]{2,10}银保监局(?:[\u4e00-\u9fff]{0,6}分局)?"
        r"|中国银保监会|中国保监会)"
    ),

    # 日期
    "publish_date": re.compile(
        r"(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日"
    ),

    # 处罚依据法条
    "legal_basis": re.compile(
        r"((?:依据|根据)\s*《[^》]{2,40}》[^\n。；;]{0,100})"
    ),
}

# 保险机构识别关键词
INSURANCE_KEYWORDS = [
    "人寿保险", "财产保险", "健康保险", "养老保险",
    "保险股份", "相互保险", "再保险", "保险代理",
    "保险经纪", "保险公估", "保险销售",
]

# 非保险机构排除关键词（降低误报）
NON_INSURANCE_KEYWORDS = [
    "银行股份", "农村商业银行", "城市商业银行",
    "消费金融", "金融租赁", "信托",
]

# 机构类型推断
INSTITUTION_TYPE_RULES = [
    ("人寿保险|寿险", "寿险公司"),
    ("财产保险|财险", "财险公司"),
    ("保险代理|保险经纪|保险公估|保险销售", "保险代理/中介"),
    ("分公司|支公司|营业部|营销服务部", "保险分支机构"),
]
